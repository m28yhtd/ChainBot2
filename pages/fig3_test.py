def replanning_node(state: SystemState) -> SystemState:
    genai.configure(api_key=GOOGLE_API_KEY)
    model = genai.GenerativeModel("gemini-2.0-flash")

    print("[replanning] 새로운 계획 생성")

    # ---- 안전한 format 유틸 (템플릿 내 임의의 { }로 인한 KeyError 방지) ----
    def safe_format(template: str, **kwargs) -> str:
        s = template.replace("{", "{{").replace("}", "}}")
        for k in kwargs.keys():
            s = s.replace("{{" + k + "}}", "{" + k + "}")
        return s.format(**kwargs)

    ZERO_WIDTH = r"[\u200B-\u200D\uFEFF]"  # 제로폭 문자, BOM 등

    def extract_xml_block(text: str, root_tag: str = "plan") -> str:
      """
      LLM 출력(코드펜스, 인용부호, 주석/잡설 포함 가능)에서
      <plan>...</plan> 블록만 안전하게 추출해 '깨끗한' XML 문자열로 반환.
      """
      s = text.strip()

      # 1) 코드펜스 제거 (```xml ... ```, ``` ... ```)
      s = re.sub(r"^```(?:xml)?\s*|\s*```$", "", s, flags=re.IGNORECASE | re.MULTILINE).strip()

      # 2) 양끝 인용부호 제거
      if (s.startswith('"') and s.endswith('"')) or (s.startswith("'") and s.endswith("'")):
        s = s[1:-1].strip()

      # 3) HTML 엔티티 복원 (&quot; → ")
      s = html.unescape(s)

      # 4) BOM/제로폭 문자 제거
      s = re.sub(ZERO_WIDTH, "", s).replace("\ufeff", "")

      # 5) 원하는 루트 태그 블록만 추출
      m = re.search(rf"<{root_tag}\b[\s\S]*?</{root_tag}>", s, flags=re.IGNORECASE)
      if not m:
        raise ValueError(f"No <{root_tag}>...</{root_tag}> block found in verified_text.")
      return m.group(0)

    def parse_plan_xml(verified_text: str) -> Tuple[ET.Element, str]:
      """
      extract_xml_block으로 뽑은 문자열을 ET로 파싱해서 (루트, 정제된문자열) 반환.
      """
      xml_str = extract_xml_block(verified_text, root_tag="plan")
      root = ET.fromstring(xml_str)  # 파싱 실패 시 ET.ParseError 발생
      return root, xml_str

    found_objects = state["found_objects"]

    # ---- 프롬프트 구성 (단일 호출) ----
    prompt_text = safe_format(
        REPLANNING_PROMPT,
        plan_prompt=DOMAIN_PROMPT5,
        instruction=state["initial_prompt"],
        initial_state=state["initial_state"],
        found_objects=found_objects,
        domain_rules=state["domain_rules"],
        example=state["example"],
        prev_plan=state["prev_plan"],
        current_state=state["current_state"],
    )

    # ---- 모델 호출 ----
    resp = model.generate_content(
        contents={"role": "user", "parts": [{"text": prompt_text}]},
        generation_config={"max_output_tokens": 4096, "temperature": 0.2}
    )
    verified_text = (resp.text or "").strip()

    state["step_index"] = 0
    root, xml_str = parse_plan_xml(verified_text)
    print("new_plan :\n", xml_str)

    state["xml_plan"] = xml_str

    apacks = root.findall(".//apack")

    # 결과 컨테이너
    apack_str_list: List[str] = []
    actions: List[str] = []
    preconds_joined: List[str] = []
    postconds_joined: List[str] = []

    for ap in apacks:
      # 1) <apack> 원문 문자열 저장
      ap_xml_str = ET.tostring(ap, encoding="unicode")
      apack_str_list.append(ap_xml_str)

      # 2) <action> 내용 추출
      action_el = ap.find("action")
      action_text = (action_el.text or "").strip() if action_el is not None else ""
      actions.append(action_text)

      # 3) <precondition> 두 개를 "\n"으로 합쳐 저장
      pre_list = [(el.text or "").strip() for el in ap.findall("precondition")]
      # 빈 문자열 제거 후 합치기
      pre_joined = "\n".join([s for s in pre_list if s])
      preconds_joined.append(pre_joined)

      # 4) <postcondition> 두 개를 "\n"으로 합쳐 저장
      post_list = [(el.text or "").strip() for el in ap.findall("postcondition")]
      post_joined = "\n".join([s for s in post_list if s])
      postconds_joined.append(post_joined)

    # ---------- SystemState 갱신 ----------
    state["apack"] = apack_str_list
    state["xml_plan_action"] = actions
    state["xml_plan_precondition"] = preconds_joined
    state["xml_plan_postcondition"] = postconds_joined

    return state

