def encode_image_to_base64(image_input) -> str:
  """
  image_input: str(path) | np.ndarray(HxWxC) | PIL.Image.Image
  반환값: data URL (e.g., 'data:image/jpeg;base64,...')
  """
  # 1) 파일 경로인 경우
  if isinstance(image_input, str) and os.path.exists(image_input):
    with open(image_input, "rb") as f:
      image_bytes = f.read()

  # 2) 넘파이 배열인 경우
  elif isinstance(image_input, np.ndarray):
    # 채널 수 정리 (RGB만 저장)
    if image_input.ndim == 3 and image_input.shape[2] >= 3:
      img = Image.fromarray(image_input[..., :3].astype("uint8"))
    else:
      # 단일 채널 등 예외 케이스는 RGB로 승격
      img = Image.fromarray(image_input.astype("uint8")).convert("RGB")
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=90)
    image_bytes = buf.getvalue()

  # 3) PIL 이미지인 경우
  elif isinstance(image_input, Image.Image):
    buf = io.BytesIO()
    image_input.convert("RGB").save(buf, format="JPEG", quality=90)
    image_bytes = buf.getvalue()

  else:
    raise TypeError("encode_image_to_base64: path(str) | numpy.ndarray | PIL.Image만 지원합니다.")

  b64 = base64.b64encode(image_bytes).decode("utf-8")
  return f"data:image/jpeg;base64,{b64}"


